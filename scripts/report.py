"""Write data/EXTRACTION_REPORT.md: per-mock completeness of the CA&GK extraction."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
mocks = json.load(open(os.path.join(ROOT, 'data', 'extracted.json')))
bank = json.load(open(os.path.join(ROOT, 'data', 'bank_full.json')))
from collections import Counter, defaultdict
st = defaultdict(Counter)
for q in bank['questions']:
    st[q['mockId']][q['status']] += 1
rows = ['| Mock id | Source PDF | Q range | Expected | Extracted | Passages | Text | Verified | Needs review | Broken |',
        '|---|---|---|---|---|---|---|---|---|---|']
tot_e = tot_x = 0
for m in sorted(mocks, key=lambda m: m['mockId']):
    a, b = m['range']; exp = b - a + 1; got = len(m.get('questions', []))
    tot_e += exp; tot_x += got
    s = st[m['mockId']]
    rows.append(f"| {m['mockId']} | {m['file']} | {a}–{b} | {exp} | {got} | {len(m.get('passages', []))} | {m.get('textQuality', 'pdf-text')} | {s['verified']} | {s['needs_review']} | {s['broken']} |")
hdr = f"# Extraction report\n\nGenerated by `scripts/report.py`. {len(mocks)} unique mock papers; {tot_x} of {tot_e} expected CA&GK questions extracted.\n\nQuestion ranges come from each paper's contents page (`Current Affairs and General Knowledge  NN-NN`). Extraction starts at the CA&GK section heading and stops at the next SECTION heading, so no questions from other sections can leak in.\n\n"
open(os.path.join(ROOT, 'data', 'EXTRACTION_REPORT.md'), 'w').write(hdr + '\n'.join(rows) + '\n')
print(hdr.splitlines()[2])
